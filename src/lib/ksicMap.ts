// 사업자번호 기준의 강제 업종 교정 규칙 (DART/공공데이터상의 어색한 업종 수동 자가치유)
export const SPECIAL_SECTOR_CORRECTIONS: Record<string, string> = {
  "1248100998": "반도체 및 전자부품 제조업", // 삼성전자 (영상기기 -> 반도체 및 전자부품 제조업)
  "1268122074": "반도체 및 전자부품 제조업", // SK하이닉스
};

/**
 * 표준산업분류(KSIC) 코드를 사람이 읽기 쉬운 표준 한글 업종명으로 변환합니다.
 */
export function getKsicName(code: string, bNo?: string): string {
  const cleanBNo = bNo ? bNo.replace(/[^0-9]/g, "") : "";
  
  // 1. 수동 자가치유 맵에 등록된 기업인지 선조회
  if (cleanBNo && SPECIAL_SECTOR_CORRECTIONS[cleanBNo]) {
    return SPECIAL_SECTOR_CORRECTIONS[cleanBNo];
  }

  if (!code) return "기타 서비스업";
  const cleanCode = code.trim();

  // 2. 맵에서 완전 일치 여부 조회
  if (KSIC_MAP[cleanCode]) return KSIC_MAP[cleanCode];

  // 3. 코드의 자릿수를 줄여가며 대분류 매칭 시도
  for (let len = cleanCode.length - 1; len >= 2; len--) {
    const subCode = cleanCode.substring(0, len);
    if (KSIC_MAP[subCode]) {
      return KSIC_MAP[subCode];
    }
  }

  // 4. 숫자로만 구성되어 있으나 매칭 안 된 경우 폴백
  if (/^[0-9]+$/.test(cleanCode)) {
    return "기타 제조업/금융업";
  }

  // 이미 한글 텍스트 명칭인 경우는 그대로 반환
  return cleanCode;
}
